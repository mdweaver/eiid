#!/usr/bin/env python3
"""Coverage self-check for the technical report.

Lists every numbered result in the PHASE documents and PACKAGE_DESIGN section 8
(R1-R18), and checks that each appears in the report's main text
(sections/*.tex) and, where the document is reproduced, in the appendices
(generated/*.tex).  Writes COVERAGE.md.   Run from docs/report:
    python3 -I tools/coverage_check.py
"""
import pathlib, re

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = HERE.parent / "extension"
DOCS = [  # (short name, file, reproduced in appendix?)
    ("PHASE1", "PHASE1_foundations.md", True),
    ("PHASE1b", "PHASE1b_monotone_did.md", False),
    ("PHASE2a", "PHASE2a_rxc.md", True),
    ("PHASE2b", "PHASE2b_districts.md", True),
    ("PHASE2c", "PHASE2c_monotone.md", True),
    ("PHASE2d", "PHASE2d_did.md", False),
    ("PHASE3", "PHASE3_inference.md", True),
    ("PHASE5a", "PHASE5a_sign_module.md", True),
    ("PACKAGE_DESIGN", "PACKAGE_DESIGN.md", True),
]
KINDS = "Lemma|Proposition|Theorem|Corollary|Conjecture|Remark|Definition"
LABEL = re.compile(r"\*\*(" + KINDS + r")\s+([A-Za-z]*[\w.\-′Δ]*[0-9′]*[\w.′]*)")

def norm_tex(s):
    s = s.replace("~", " ").replace("$'$", "′").replace("$\\Delta$", "Δ").replace("\\Delta", "Δ")
    s = s.replace("\\,", " ").replace("\\ ", " ")
    for a, b in [("Prop. ", "Proposition "), ("Props ", "Proposition "), ("Thm ", "Theorem "),
                 ("Cor. ", "Corollary "), ("Rem. ", "Remark "), ("Remarks ", "Remark "),
                 ("Lemmas ", "Lemma "), ("Propositions ", "Proposition "), ("Theorems ", "Theorem ")]:
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s)

def extract(doc):
    text = (SRC / doc).read_text(encoding="utf-8")
    found = []
    for m in LABEL.finditer(text):
        kind, num = m.group(1), m.group(2).rstrip(".:")
        if not num or not re.search(r"[0-9′]", num) and kind != "Definition":
            if kind == "Definition" and not num:
                num = "(unnumbered)"
            elif not re.search(r"[0-9′]", num or ""):
                continue
        key = f"{kind} {num}"
        if key not in found:
            found.append(key)
    return found

def present(key, corpus):
    kind, num = key.split(" ", 1)
    if num == "(unnumbered)":
        return True
    # accept "Kind num", or "num" next to a closely related word (e.g. "Propositions D5, D6")
    pats = [re.escape(f"{kind} {num}")]
    if re.match(r"[A-Za-zΔ]", num):  # lettered labels (D5, M3, N2.2, P3.2, R3, FD2) are unambiguous
        pats.append(r"(?<![\w.])" + re.escape(num) + r"(?![\w′])")
    hits = [p for p in pats if re.search(p, corpus)]
    return bool(hits)

def main():
    main_txt = norm_tex("\n".join(p.read_text() for p in sorted((HERE / "sections").glob("*.tex"))))
    app_txt = norm_tex("\n".join(p.read_text() for p in sorted((HERE / "generated").glob("*.tex"))))
    lines = ["# Coverage self-check", "",
             "Generated by `tools/coverage_check.py`. For each numbered result (bold label) in the",
             "source documents, and for each proof-register item R1-R18 of PACKAGE_DESIGN §8: whether",
             "it appears in the report's main text (`sections/*.tex`) and in the reproduced appendices",
             "(`generated/*.tex`). PHASE1b and PHASE2d are proposals, not reviewed and not reproduced;",
             "their results are listed in Section 9 and the status table only.", ""]
    total = miss = 0
    for short, doc, repro in DOCS:
        keys = extract(doc)
        lines += [f"## {short} (`{doc}`)", "", "| Result | Main text | Appendix |", "|---|---|---|"]
        for k in keys:
            total += 1
            m = present(k, main_txt)
            a = present(k, app_txt) if repro else None
            if not m:
                miss += 1
            lines.append(f"| {k} | {'yes' if m else '**MISSING**'} | "
                         f"{'yes' if a else ('n/a (not reproduced)' if a is None else '**MISSING**')} |")
        if short == "PHASE1b":
            # PHASE1b is a proposal organised by section headings, not bold result labels
            secs = re.findall(r"^## ([AB][0-9])\. ", (SRC / doc).read_text(encoding="utf-8"), re.M)
            ok = "A1--A5" in main_txt and "B1--B5" in main_txt
            for sec in secs:
                total += 1
                if not ok:
                    miss += 1
                lines.append(f"| §{sec} (proposal section) | {'yes (Section 9, status table)' if ok else '**MISSING**'} | n/a (not reproduced) |")
        lines.append("")
    # proof register
    lines += ["## PACKAGE_DESIGN §8 proof register", "", "| Item | Main text | Appendix |", "|---|---|---|"]
    for i in range(1, 19):
        total += 1
        k = f"R{i}"
        m = re.search(r"(?<![\w-])" + k + r"(?![0-9])", main_txt) is not None
        a = re.search(r"(?<![\w-])" + k + r"(?![0-9])", app_txt) is not None
        if not m:
            miss += 1
        lines.append(f"| {k} | {'yes' if m else '**MISSING**'} | {'yes' if a else '**MISSING**'} |")
    lines += ["", f"**Summary:** {total} items checked; {total - miss} found in the main text; "
              f"{miss} missing.", ""]
    (HERE / "COVERAGE.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{total} items, {miss} missing from main text")

if __name__ == "__main__":
    main()
