#!/usr/bin/env python3
"""Reproduce the repository's theory documents as LaTeX appendices.

The appendices of the technical report are *verbatim conversions* (pandoc)
of the Markdown sources in docs/extension, at the commit the report is pinned
to.  Nothing is rewritten: proofs, tags and correction notes appear exactly as
in the source.  Run from docs/report:  python3 -I tools/make_appendices.py
"""
import pathlib, re, subprocess, sys

HERE = pathlib.Path(__file__).resolve().parent.parent      # docs/report
SRC = HERE.parent / "extension"
OUT = HERE / "generated"

# (output name, source file, id prefix, optional list of top-level '## ' headings to keep)
JOBS = [
    ("app_phase1", "PHASE1_foundations.md", "pA-", None),
    ("app_phase2a", "PHASE2a_rxc.md", "pB-", None),
    ("app_phase2b", "PHASE2b_districts.md", "pC-", None),
    ("app_phase2c", "PHASE2c_monotone.md", "pD-", None),
    ("app_phase3", "PHASE3_inference.md", "pE-", None),
    ("app_phase5a", "PHASE5a_sign_module.md", "pF-", None),
    ("app_pkgdesign", "PACKAGE_DESIGN.md", "pG-",
     ["## 2. Audit of the GPT conversation", "## 5. New results for the extension modules",
      "## 8. Proof register"]),
]

def select_sections(text, keep):
    """Keep the title line and the '## ' sections whose heading starts with an entry of keep."""
    if keep is None:
        return text
    lines = text.splitlines()
    out, on = [lines[0]], False
    for ln in lines[1:]:
        if ln.startswith("## "):
            on = any(ln.startswith(k) for k in keep)
        if on:
            out.append(ln)
    return "\n".join(out) + "\n"

def convert(name, src, prefix, keep):
    text = (SRC / src).read_text(encoding="utf-8")
    text = select_sections(text, keep)
    # drop the document title: the appendix supplies its own heading
    text = re.sub(r"\A# .*\n", "", text)
    res = subprocess.run(
        ["pandoc", "-f", "markdown+tex_math_dollars-implicit_figures", "-t", "latex",
         f"--id-prefix={prefix}", "--wrap=preserve"],
        input=text, capture_output=True, text=True, check=True)
    tex = res.stdout
    # combining accents (rare) cannot be typeset by pdflatex: drop them
    tex = tex.replace("̃", "").replace("̄", "")
    # make anchors unique across appendices (pandoc's --id-prefix does not reach \label)
    for cmd in ("\\hypertarget{", "\\label{", "\\hyperlink{"):
        tex = tex.replace(cmd, cmd + prefix)
    header = (f"% GENERATED by tools/make_appendices.py from docs/extension/{src}\n"
              f"% Do not edit by hand; edit the source and regenerate.\n")
    (OUT / f"{name}.tex").write_text(header + tex, encoding="utf-8")
    print(f"{name}: {len(tex.splitlines())} lines")

if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    for job in JOBS:
        convert(*job)
